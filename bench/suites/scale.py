async def _peer() -> PeerClient:
    """The peer, or a Skip explaining how to start one."""
    client = PeerClient.from_environment()
    if client is None:
        raise Skip(
            "no A11_BENCH_PEER=host:port -- start `python -m bench.peer` on"
            " the host that is to be the server"
        )
    try:
        await client.connect()
    except (OSError, asyncio.TimeoutError) as unreachable:
        raise Skip(
            f"peer at {client.host}:{client.port} is unreachable"
            f" ({unreachable!r})"
        ) from unreachable
    return client

SUITE = "scale"

#: How long each measured window runs. Long enough that a 30k-session ramp step
#: is not dominated by its own setup, short enough that a full ramp fits in a
#: coffee break.
_WINDOW_SECONDS = 6.0

#: Per-operation deadline. Generous: at 30k sessions a p99.9 of seconds is a
#: finding, not a failure, and a tight timeout would convert it into one.
_OP_TIMEOUT = 30.0

#: Connect concurrency per worker. Sessions are established in waves rather than
#: all at once, because `somaxconn` is 4096 by default and a 30k-wide SYN burst
#: is dropped by the kernel rather than queued.
_CONNECT_WAVE = 64

#: How long the parent waits for its client workers before giving up on them.
#: A ceiling on the whole step, not per session: exceeding it is reported as a
#: result rather than hanging the suite.
_LAUNCH_TIMEOUT = 420.0


# ---------------------------------------------------------------------------
# Preflight: the limits that cap a population before A11 does
# ---------------------------------------------------------------------------


@dataclass
class Limits:
    """What the host will allow, and therefore what a ramp may ask for."""

    open_files: int
    port_range: tuple[int, int] | None
    somaxconn: int | None
    cores: int
    notes: list[str] = field(default_factory=list)

    @property
    def ephemeral_ports(self) -> int | None:
        if self.port_range is None:
            return None
        low, high = self.port_range
        return max(0, high - low + 1)

    def max_sessions(self, server_ports: int) -> int:
        """The ceiling this host imposes on one client address."""
        by_fd = max(0, self.open_files - 256)  # listeners, logs, the runtime
        ports = self.ephemeral_ports
        by_port = by_fd if ports is None else ports * server_ports
        return min(by_fd, by_port)


def _read_int(path: str) -> int | None:
    try:
        with open(path, encoding="utf-8") as handle:
            return int(handle.read().split()[0])
    except (OSError, ValueError, IndexError):
        return None


def preflight(target_sessions: int, server_ports: int) -> Limits:
    """Read the host's limits and explain any that the target would exceed.

    Deliberately does not *raise*: a run that cannot reach 30k on this host is
    still worth doing at whatever it can reach, and a hard failure would hide
    the rest of the ramp. The notes travel with the result so a number is never
    read as an A11 ceiling when it was a `ulimit`.
    """
    import resource

    soft, _hard = resource.getlimit(resource.RLIMIT_NOFILE) if hasattr(
        resource, "getlimit"
    ) else resource.getrlimit(resource.RLIMIT_NOFILE)
    port_range: tuple[int, int] | None = None
    somaxconn: int | None = None
    if platform.system() == "Linux":
        low = _read_int("/proc/sys/net/ipv4/ip_local_port_range")
        somaxconn = _read_int("/proc/sys/net/core/somaxconn")
        try:
            with open(
                "/proc/sys/net/ipv4/ip_local_port_range", encoding="utf-8"
            ) as handle:
                parts = handle.read().split()
                port_range = (int(parts[0]), int(parts[1]))
        except (OSError, ValueError, IndexError):
            port_range = (low, low) if low else None

    limits = Limits(
        open_files=int(soft),
        port_range=port_range,
        somaxconn=somaxconn,
        cores=os.cpu_count() or 1,
    )

    ceiling = limits.max_sessions(server_ports)
    if ceiling < target_sessions:
        limits.notes.append(
            f"host caps this client at ~{ceiling} sessions "
            f"(ulimit -n {limits.open_files}, "
            f"{limits.ephemeral_ports} ephemeral ports x {server_ports} "
            f"server ports); asked for {target_sessions}"
        )
    if limits.open_files < target_sessions + 256:
        limits.notes.append(
            f"raise ulimit -n above {target_sessions + 256} "
            f"(currently {limits.open_files})"
        )
    if limits.somaxconn is not None and limits.somaxconn < _CONNECT_WAVE * 4:
        limits.notes.append(
            f"somaxconn is {limits.somaxconn}; connect waves are "
            f"{_CONNECT_WAVE}, so the accept queue is the pacing limit"
        )
    return limits


# ---------------------------------------------------------------------------
# The populations
# ---------------------------------------------------------------------------

#: What each population does per operation, and why it is in the mixture.
#:
#: `idle` holds a session and never speaks: it prices the *existence* of a
#: session, which is what 30k users mostly are. `rpc` is the one whose latency
#: matters and the one that starves. `bulk` moves 64 KiB. `compute` asks the
#: server to hash, which is the only population the pool cannot overlap away.
POPULATIONS = ("idle", "rpc", "bulk", "compute")


@dataclass
class Mix:
    """How a population of `total` sessions is divided."""

    idle: int
    rpc: int
    bulk: int
    compute: int

    @classmethod
    def realistic(cls, total: int) -> "Mix":
        """Mostly idle, which is what a real user population looks like.

        90% holding a session and doing nothing, 7% small calls, 2% moving
        payload, 1% computing. The active fraction is what the server actually
        feels; the idle fraction is what its memory feels.
        """
        rpc = max(1, int(total * 0.07))
        bulk = max(1, int(total * 0.02))
        compute = max(1, int(total * 0.01))
        idle = max(0, total - rpc - bulk - compute)
        return cls(idle=idle, rpc=rpc, bulk=bulk, compute=compute)

    def counts(self) -> dict[str, int]:
        return {
            "idle": self.idle,
            "rpc": self.rpc,
            "bulk": self.bulk,
            "compute": self.compute,
        }

    @property
    def total(self) -> int:
        return self.idle + self.rpc + self.bulk + self.compute


# ---------------------------------------------------------------------------
# The client worker: one process, its own slice of the population
# ---------------------------------------------------------------------------


@dataclass
class Slice:
    """What one worker process is asked to hold and do."""

    worker: int
    host: str
    ports: list[int]
    transport: str
    counts: dict[str, int]
    window_seconds: float
    bulk_bytes: int
    compute_rounds: int


def _stream(host: str, port: int, transport: str):
    if transport == "websocket":
        options = net.WebSocketClientOptions()
        # Mirror the server: it speaks HTTP/1.1 here, and a client that offers
        # h2 spends the handshake discovering that.
        options.http2_options.enable_h2 = False
        options.http2_options.enable_h2c = False
        return net.WebSocketWireStream.connect(
            f"ws://{host}:{port}/bench", websocket_options=options
        )
    if transport == "sse":
        return net.HttpSseClientWireStream(f"http://{host}:{port}")
    raise ValueError(transport)


class _Session:
    """One client session, plus which population it belongs to."""

    __slots__ = ("population", "session", "stream")

    def __init__(self, population: str, session, stream) -> None:
        self.population = population
        self.session = session
        self.stream = stream


async def _open(host: str, port: int, transport: str, population: str):
    stream = _stream(host, port, transport)
    session = a11.Session(action_registry=a11.ActionRegistry())
    await asyncio.wait_for(
        session.add_stream(stream, mode="start"), timeout=_OP_TIMEOUT
    )
    return _Session(population, session, stream)


def _call(item: _Session, schema):
    """A call bound to this session, the way `bench/suites/server.py` does it.

    An Action is created client-side and bound to the node map, the session and
    the stream; there is no `session.call` convenience, and inventing one is how
    the first version of this file failed.
    """
    return (
        a11.Action(schema)
        .bind_node_map(item.session.node_map)
        .bind_session(item.session)
        .bind_stream(item.stream)
    )


async def _one_rpc(item: _Session) -> None:
    call = _call(item, peer_mod.ECHO)
    await call.call()
    await call["text"].finalize("ping")
    await call["out"].consume(str)
    await call.wait(_OP_TIMEOUT)


async def _one_bulk(item: _Session, payload: bytes) -> None:
    call = _call(item, peer_mod.SINK)
    await call.call()
    await call["data"].finalize(
        types.Chunk(
            data=payload,
            metadata=types.ChunkMetadata(mimetype="application/octet-stream"),
        )
    )
    await call["report"].consume(dict)
    await call.wait(_OP_TIMEOUT)


async def _one_compute(item: _Session, rounds: int) -> None:
    call = _call(item, peer_mod.COMPUTE)
    await call.call()
    await call["request"].finalize({"rounds": rounds, "size": 4096})
    await call["report"].consume(dict)
    await call.wait(_OP_TIMEOUT)


async def _drive(item: _Session, slice_: Slice, deadline: float,
                 samples: list[float], failures: list[str]) -> None:
    """Call in a loop until the window closes, recording each latency."""
    payload = b"b" * slice_.bulk_bytes
    while time.perf_counter() < deadline:
        started = time.perf_counter()
        try:
            if item.population == "rpc":
                await _one_rpc(item)
            elif item.population == "bulk":
                await _one_bulk(item, payload)
            elif item.population == "compute":
                await _one_compute(item, slice_.compute_rounds)
            else:
                return  # idle holds the session and nothing else
        except Exception as error:  # noqa: BLE001 - a failure is a datum here
            failures.append(f"{type(error).__name__}: {error}"[:160])
            # Keep going: at scale the interesting question is what fraction
            # fails, not the first one that does.
            await asyncio.sleep(0.05)
            continue
        samples.append((time.perf_counter() - started) * 1e6)


async def _run_slice(slice_: Slice) -> dict[str, Any]:
    sessions: list[_Session] = []
    connect_failures: list[str] = []
    connect_started = time.perf_counter()

    # Connect in waves, round-robin across the server ports so no single
    # ip:port pair exhausts its ephemeral range.
    wanted: list[str] = []
    for population, count in slice_.counts.items():
        wanted.extend([population] * count)

    async def open_one(index: int, population: str) -> None:
        port = slice_.ports[index % len(slice_.ports)]
        try:
            sessions.append(
                await _open(slice_.host, port, slice_.transport, population)
            )
        except Exception as error:  # noqa: BLE001
            connect_failures.append(f"{type(error).__name__}: {error}"[:160])

    slowest_wave = 0.0
    for start in range(0, len(wanted), _CONNECT_WAVE):
        chunk = wanted[start : start + _CONNECT_WAVE]
        wave_started = time.perf_counter()
        await asyncio.gather(
            *(open_one(start + offset, population)
              for offset, population in enumerate(chunk))
        )
        slowest_wave = max(slowest_wave, time.perf_counter() - wave_started)
    connect_seconds = time.perf_counter() - connect_started

    samples: dict[str, list[float]] = {name: [] for name in POPULATIONS}
    failures: dict[str, list[str]] = {name: [] for name in POPULATIONS}
    deadline = time.perf_counter() + slice_.window_seconds
    await asyncio.gather(
        *(
            _drive(item, slice_, deadline, samples[item.population],
                   failures[item.population])
            for item in sessions
        )
    )

    for item in sessions:
        with contextlib.suppress(Exception):
            await item.stream.abort()

    return {
        "worker": slice_.worker,
        "sessions": len(sessions),
        "connect_seconds": connect_seconds,
        "slowest_wave_seconds": slowest_wave,
        "connect_failures": connect_failures[:5],
        "connect_failure_count": len(connect_failures),
        "samples": {name: values for name, values in samples.items()},
        "failures": {
            name: values[:3] for name, values in failures.items() if values
        },
        "failure_counts": {
            name: len(values) for name, values in failures.items()
        },
    }


def _worker_entry(payload: dict[str, Any], results) -> None:
    """Process entry point. Deliberately tiny: everything else is async.

    The pool width is pinned *before* a11 is touched. Each worker process brings
    its own A11 runtime -- a uv loop and a worker pool -- and a default pool is
    `hardware_concurrency()` wide, so twelve workers on a twelve-core box asked
    for 144 pool threads and then competed with the server for the same cores.
    The first run of this suite spent 60 seconds establishing 419 of 1000
    sessions because of it.
    """
    os.environ.setdefault("A11_POOL_THREADS", "2")
    slice_ = Slice(**payload)
    try:
        results.put(asyncio.run(_run_slice(slice_)))
    except Exception as error:  # noqa: BLE001
        results.put({"worker": slice_.worker, "fatal": f"{type(error).__name__}: {error}"})


