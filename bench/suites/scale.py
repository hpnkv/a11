"""A11 under a population, not a handful of clients.

The `server` suite runs four client populations of four members each and finds a
capacity knee at 64 clients. This one asks the question a deployment asks: what
happens with **tens of thousands** of sessions, most of them idle, some sending
payload, some calling actions, and some asking the server to *compute* rather
than to wait.

Three things make this different from `server`, and each of them is a constraint
that bites before A11 does:

* **One asyncio process cannot drive tens of thousands of sessions.** Load is
  generated by worker *processes*, one per core by default, each holding its own
  slice of the population. A single-process ramp measures the client.
* **Ephemeral ports run out before descriptors do.** One client address to one
  server `ip:port` gives about 28k tuples on a default Linux
  (`net.ipv4.ip_local_port_range`), so a 30k-session run *must* spread across
  several server ports. `preflight()` computes the ceiling and says so rather
  than letting a run stall at 28k and look like an A11 limit.
* **The interesting number is not throughput.** It is whether the 5.5-7.1x
  small-request starvation in `FINDINGS.md` item 0b gets worse as the population
  grows, and what the tail does. Both are reported per population at every step
  of the ramp.

Skips cleanly without `A11_BENCH_PEER`, like `link` and `server`.
"""

