def _percentiles(values: list[float]) -> dict[str, float]:
    if not values:
        return {}
    ordered = sorted(values)

    def at(fraction: float) -> float:
        index = min(len(ordered) - 1, int(fraction * len(ordered)))
        return ordered[index]

    return {
        "p50_us": at(0.50),
        "p90_us": at(0.90),
        "p99_us": at(0.99),
        "p999_us": at(0.999),
        "max_us": ordered[-1],
    }


async def _start_services(peer: PeerClient, transport: str,
                          count: int) -> list[int]:
    """One listener per `count`, because one is not enough tuple space.

    Returns the ports. Several listeners on the server is the cheapest way to
    multiply the client's ephemeral range, and it costs the server nothing but a
    socket -- the sessions land in the same process either way.
    """
    ports: list[int] = []
    for _index in range(count):
        started = await peer.call("service", transport=transport, port=0)
        ports.append(int(started["port"]))
    return ports


def _launch(slices: list[Slice]) -> list[dict[str, Any]]:
    """Run every slice in its own process and collect the results.

    `spawn` rather than `fork`: the parent has an asyncio loop and native
    threads (the uv loop, the worker pool) running, and forking a process with
    those is how a benchmark acquires a mystery deadlock.
    """
    context = multiprocessing.get_context("spawn")
    results = context.Queue()
    processes = []
    for slice_ in slices:
        payload = dict(vars(slice_))
        process = context.Process(
            target=_worker_entry, args=(payload, results), daemon=True
        )
        process.start()
        processes.append(process)

    # Collected by polling rather than by a long blocking get, because a worker
    # that dies without posting a result would otherwise hang the parent for the
    # whole timeout -- and a worker holding thousands of sessions has plenty of
    # ways to die (a descriptor limit, the OOM killer, a native abort). The loop
    # exits as soon as every process is either accounted for or gone.
    import queue as queue_module

    collected: list[dict[str, Any]] = []
    deadline = time.monotonic() + _LAUNCH_TIMEOUT
    while len(collected) < len(processes) and time.monotonic() < deadline:
        try:
            collected.append(results.get(timeout=1.0))
            continue
        except queue_module.Empty:
            pass
        alive = sum(1 for process in processes if process.is_alive())
        if alive == 0:
            # Everyone has exited; drain anything still in flight and stop.
            while len(collected) < len(processes):
                try:
                    collected.append(results.get(timeout=1.0))
                except queue_module.Empty:
                    break
            break
    for process in processes:
        if process.is_alive():
            process.terminate()
        process.join(timeout=10)
    missing = len(processes) - len(collected)
    if missing > 0:
        collected.append({
            "worker": -1,
            "fatal": f"{missing} of {len(processes)} client workers produced no "
                     f"result (died or exceeded {_LAUNCH_TIMEOUT:.0f}s)",
        })
    return collected


def _merge(collected: list[dict[str, Any]]) -> dict[str, Any]:
    samples: dict[str, list[float]] = {name: [] for name in POPULATIONS}
    failure_counts: dict[str, int] = {name: 0 for name in POPULATIONS}
    examples: list[str] = []
    sessions = 0
    connect_failures = 0
    connect_seconds = 0.0
    slowest_wave = 0.0
    fatal: list[str] = []
    for one in collected:
        if "fatal" in one:
            fatal.append(one["fatal"])
            continue
        sessions += one["sessions"]
        connect_failures += one["connect_failure_count"]
        connect_seconds = max(connect_seconds, one["connect_seconds"])
        slowest_wave = max(slowest_wave, one.get("slowest_wave_seconds", 0.0))
        for name in POPULATIONS:
            samples[name].extend(one["samples"].get(name, []))
            failure_counts[name] += one["failure_counts"].get(name, 0)
        for values in one.get("failures", {}).values():
            examples.extend(values)
        examples.extend(one.get("connect_failures", []))
    return {
        "sessions": sessions,
        "connect_failures": connect_failures,
        "connect_seconds": connect_seconds,
        "slowest_wave_seconds": slowest_wave,
        "samples": samples,
        "failure_counts": failure_counts,
        "examples": examples[:4],
        "fatal": fatal,
    }


@benchmark(SUITE, "population_ramp", slow=True)
async def population_ramp(scale: float) -> list[Result]:
    """Hold a growing population and report what each part of it experiences.

    The ramp is in *sessions*, not in request rate: the question is what the
    population costs to have, and how the small-request latency behaves as it
    grows. `--scale` moves the top of the ramp, so a quick pass can stop at 1k
    and a real one can go to 30k.
    """
    peer = await _peer()
    transport = "websocket"
    steps = [100, 1_000, 10_000, 30_000]
    top = max(1, int(30_000 * scale)) if scale < 1.0 else 30_000
    steps = [step for step in steps if step <= top] or [steps[0]]

    # Overridable so the multi-process machinery can be isolated from A11: a
    # single worker driving the same population tells you whether a shortfall is
    # the harness or the runtime.
    workers = max(1, min(os.cpu_count() or 1, 12))
    if (override := os.environ.get("A11_SCALE_WORKERS")) is not None:
        workers = max(1, int(override))
    results: list[Result] = []

    try:
        for target in steps:
            # More listeners as the population grows: one per ~8k sessions keeps
            # every client ip:port pair well inside its ephemeral range.
            server_ports = max(1, (target + 7_999) // 8_000)
            limits = preflight(target, server_ports)
            ports = await _start_services(peer, transport, server_ports)

            mix = Mix.realistic(target)
            # Round-robin, not integer division with the remainder dumped on
            # worker 0: at small totals `rpc` is fewer than the worker count, so
            # division gives every worker zero and one worker all of them -- and
            # if that worker dies the population has no samples at all, which is
            # exactly how the first run of this suite reported nothing.
            per_worker: list[dict[str, int]] = [
                {name: 0 for name in POPULATIONS} for _index in range(workers)
            ]
            for name, count in mix.counts().items():
                for index in range(count):
                    per_worker[index % workers][name] += 1

            slices = [
                Slice(
                    worker=index,
                    host=peer.host,
                    ports=ports,
                    transport=transport,
                    counts=per_worker[index],
                    window_seconds=_WINDOW_SECONDS,
                    bulk_bytes=64 * 1024,
                    compute_rounds=64,
                )
                for index in range(workers)
            ]

            before = await peer.call("stats")
            peak: dict[str, float] = {}
            sampler = asyncio.create_task(
                _sample_server(peer.host, peer.port, peak)
            )
            try:
                merged = _merge(await asyncio.to_thread(_launch, slices))
            finally:
                sampler.cancel()
                with contextlib.suppress(asyncio.CancelledError):
                    await sampler
            # A dead peer must not cost the whole ramp. This has happened: a
            # stray SIGTERM to the agent turned a completed 1000-session step
            # into `ConnectionError: peer closed while answering 'stats'` and
            # zero rows, discarding measurements that had already been taken.
            try:
                after = await peer.call("stats")
            except Exception as gone:  # noqa: BLE001 - the run is the datum
                after = {}
                note_peer_died = f"peer unreachable after the window ({gone!r})"
            else:
                note_peer_died = ""

            cost = _server_delta(before, after)
            cost.update(peak)
            note_parts = list(limits.notes)
            if note_peer_died:
                note_parts.append(note_peer_died)
            if merged["fatal"]:
                note_parts.append("worker fatal: " + "; ".join(merged["fatal"][:2]))
            if merged["examples"]:
                note_parts.append("examples: " + " | ".join(merged["examples"]))

            for name in POPULATIONS:
                values = merged["samples"][name]
                metrics: dict[str, float] = {
                    "sessions": float(mix.counts()[name]),
                    "completed": float(len(values)),
                    "failures": float(merged["failure_counts"][name]),
                }
                if values:
                    metrics["ops_per_s"] = len(values) / _WINDOW_SECONDS
                    metrics.update(_percentiles(values))
                results.append(
                    Result(
                        suite=SUITE,
                        name="population_ramp",
                        metrics=metrics,
                        params={
                            "population": name,
                            "sessions_total": target,
                            "transport": transport,
                        },
                        note="; ".join(note_parts),
                    )
                )

            results.append(
                Result(
                    suite=SUITE,
                    name="population_cost",
                    metrics={
                        "sessions_established": float(merged["sessions"]),
                        "sessions_asked": float(target),
                        "connect_failures": float(merged["connect_failures"]),
                        "connect_seconds": merged["connect_seconds"],
                        "slowest_wave_seconds": merged["slowest_wave_seconds"],
                        "server_ports": float(server_ports),
                        "client_workers": float(workers),
                        **cost,
                    },
                    params={"sessions_total": target, "transport": transport},
                    note="; ".join(note_parts),
                )
            )

            if note_peer_died:
                # Nothing further can be measured against an agent that is gone,
                # but what was measured is already in `results`.
                break
            await peer.call("teardown")
    finally:
        await peer.aclose()
    return results


async def _sample_server(host: str, port: int, peak: dict[str, float]) -> None:
    """Poll the server while the population is live, keeping the peaks.

    Necessary because the interesting quantities -- descriptors held, resident
    bytes, sessions -- are properties of the *live* population, and every worker
    aborts its streams before it reports. Sampling afterwards measures a server
    that has just been emptied, which is why the first run reported 19
    descriptors while holding 419 sessions.

    On its **own** control connection, not the caller's: `PeerClient` is one
    socket with request/response framing and no mutex, so two coroutines sharing
    one read each other's replies. That failed as
    `list indices must be integers` -- a mis-framed response, not a type bug.
    """
    sampler = PeerClient(host, port)
    try:
        await sampler.connect()
    except Exception:  # noqa: BLE001 - sampling is optional
        return
    try:
        while True:
            try:
                stats = await sampler.call("stats")
            except Exception:  # noqa: BLE001 - a missed sample is not a failure
                await asyncio.sleep(0.5)
                continue
            if isinstance(stats, dict):
                for key, name in (
                    ("open_files", "server_open_files_peak"),
                    ("rss_bytes", "server_rss_bytes_peak"),
                    ("sessions", "server_sessions_peak"),
                ):
                    if key in stats:
                        peak[name] = max(peak.get(name, 0.0), float(stats[key]))
            await asyncio.sleep(0.5)
    finally:
        with contextlib.suppress(Exception):
            await sampler.aclose()


def _server_delta(before: dict[str, Any], after: dict[str, Any]) -> dict[str, float]:
    """What the server spent, from its own accounting."""
    out: dict[str, float] = {}
    cpu_before = float(before.get("cpu_s", 0.0))
    cpu_after = float(after.get("cpu_s", 0.0))
    if cpu_after >= cpu_before:
        out["server_cpu_s"] = cpu_after - cpu_before
        out["server_cores_busy"] = (cpu_after - cpu_before) / _WINDOW_SECONDS
    for key, name in (
        ("rss_bytes", "server_rss_bytes"),
        ("open_files", "server_open_files"),
        ("sessions", "server_sessions"),
    ):
        if key in after:
            out[name] = float(after[key])
    return out
