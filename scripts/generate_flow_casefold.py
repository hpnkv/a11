"""Regenerate Flow's Unicode full-casefold table with Python Unicode 17.0.0."""

import unicodedata
from pathlib import Path

UNICODE_VERSION = "17.0.0"
DESTINATION = (
    Path(__file__).resolve().parents[1]
    / "cpp/a11/flow/casefold_data.inc"
)


def main() -> None:
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise SystemExit(
            f"Python Unicode {UNICODE_VERSION} required; "
            f"found {unicodedata.unidata_version}"
        )
    lines = [
        "// Generated by scripts/generate_flow_casefold.py; Unicode 17.0.0.\n"
    ]
    for point in range(0x110000):
        character = chr(point)
        folded = character.casefold()
        if folded == character:
            continue
        escaped = "".join(f"\\x{byte:02X}" for byte in folded.encode("utf-8"))
        lines.append(f'    {{0x{point:06X}U, "{escaped}"}},\n')
    DESTINATION.write_text("".join(lines), encoding="ascii")


if __name__ == "__main__":
    main()
